"""Turn the chosen candidate pictures into a Kohya training folder.

`selected.txt` (picture numbers, any whitespace) is written by the person who
looked at the contact sheets. Each chosen picture gets a caption of the trigger
word plus only the tags that vary (framing, place, mood); the fixed look is
left out so the LoRA learns it as the meaning of the trigger word.

    python -m animeforge.cluster.lora_prep <lora dir> <trigger>
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path


def main() -> None:
    root, trigger = Path(sys.argv[1]), sys.argv[2]
    data = json.loads((root / "candidates.json").read_text())
    chosen = {int(n) for n in (root / "selected.txt").read_text().split()}
    train = root / f"train-{trigger}"
    train.mkdir(exist_ok=True)
    for old in train.iterdir():          # a rerun with a new choice starts clean
        old.unlink()
    used = []
    for r in data["pictures"]:
        if r["n"] not in chosen:
            continue
        shutil.copy(root / "candidates" / r["file"], train / r["file"])
        (train / r["file"]).with_suffix(".txt").write_text(f"{trigger}, 1boy, solo, {r['tags']}")
        used.append(r)
    if len(used) < 12:
        raise SystemExit(f"only {len(used)} pictures chosen; a character LoRA needs at least 12")
    (root / "dataset.toml").write_text(
        "[general]\nenable_bucket = true\ncaption_extension = \".txt\"\n\n"
        "[[datasets]]\nresolution = 1024\nbatch_size = 2\nmin_bucket_reso = 640\nmax_bucket_reso = 1536\n\n"
        f"[[datasets.subsets]]\nimage_dir = \"{train}\"\nnum_repeats = 10\n")
    (root / "training_set.json").write_text(json.dumps(
        {"trigger": trigger, "character": data["character"], "count": len(used),
         "origin": "generated by this project from its own prompts with a cleared model; chosen by eye",
         "pictures": used}, indent=1))
    print(len(used), "training pictures")


if __name__ == "__main__":
    main()
